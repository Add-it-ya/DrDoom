"""Measure how often each way of deciding risk rates a plan below what it deserves.

Run with ``python -m drdoom.evals.risk``; add ``--record`` with a configured provider to
refresh the assessor's recorded answers.

Under-rating is the error that matters: a plan rated below its real risk can run without
a human. Over-rating costs one click. Each case carries the rating it should have, and
three ways of deciding are scored against it:

- the author alone, which is how the system decided before the assessor existed
- the author and the policy floor, which needs no model
- all three, the rule the service now runs

The first two need no model and are always measured. The third needs the assessor's
answers; without recorded ones it is reported as not measured rather than scored as if
every answer had been "high", which would flatter it.
"""

from __future__ import annotations

import argparse
import json
import logging
from dataclasses import dataclass
from pathlib import Path

from drdoom.agents.risk import ORDER, RiskAssessor, highest
from drdoom.agents.schemas import Diagnosis, RemediationPlan
from drdoom.config import get_settings
from drdoom.executor import DryRunExecutor, risk_floor
from drdoom.llm.base import LLMProvider
from drdoom.llm.recording import RecordingProvider, ReplayProvider, SnapshotStore

logger = logging.getLogger(__name__)

RULES = ("author", "author_and_floor", "all_three")
LABELS = {
    "author": "Author alone (before)",
    "author_and_floor": "Author and policy floor",
    "all_three": "Author, floor and assessor (now)",
}


def cases_path() -> Path:
    return get_settings().project_root / "evals" / "risk_cases.json"


def snapshot_dir() -> Path:
    return get_settings().project_root / "evals" / "snapshots" / "risk"


def load_cases(path: Path | None = None) -> list[dict]:
    return json.loads((path or cases_path()).read_text(encoding="utf-8"))["cases"]


@dataclass(frozen=True)
class CaseResult:
    case_id: str
    expected: str
    author: str
    floor: str
    assessor: str | None

    def rating(self, rule: str) -> str | None:
        if rule == "author":
            return self.author
        if rule == "author_and_floor":
            return highest(self.author, self.floor)
        if self.assessor is None:
            return None
        return highest(self.author, self.floor, self.assessor)


def run_case(assessor: RiskAssessor, case: dict) -> CaseResult:
    plan = RemediationPlan.model_validate(case["plan"])
    outcome = assessor.run(
        case["triage"],
        Diagnosis.model_validate(case["diagnosis"]),
        plan,
        DryRunExecutor().preview(plan),
        [],
    )
    return CaseResult(
        case_id=case["id"],
        expected=case["expected"],
        author=plan.risk_level,
        floor=risk_floor(plan.action),
        assessor=outcome.assessment.risk_level if outcome.assessment else None,
    )


def summarise(results: list[CaseResult]) -> dict[str, dict]:
    """Per rule: how many cases it rated, and how many it rated too low or too high."""
    summary: dict[str, dict] = {}
    for rule in RULES:
        rated = [(r, r.rating(rule)) for r in results if r.rating(rule) is not None]
        summary[rule] = {
            "rated": len(rated),
            "under": sum(ORDER[level] < ORDER[r.expected] for r, level in rated),
            "over": sum(ORDER[level] > ORDER[r.expected] for r, level in rated),
            "under_ids": [r.case_id for r, level in rated if ORDER[level] < ORDER[r.expected]],
        }
    summary["assessor_answered"] = {"rated": sum(r.assessor is not None for r in results)}
    return summary


def render(summary: dict[str, dict], results: list[CaseResult]) -> str:
    total = len(results)
    lines = [
        "# Risk rating evaluation",
        "",
        "Generated by `python -m drdoom.evals.risk` from `evals/risk_cases.json`.",
        "",
        "Each case is a remediation plan with the rating it should carry. *Under* means the",
        "rule rated it below that, which can let it run without a human; *over* means above,",
        "which costs a click. The author ratings in the set are written by hand and several",
        "are deliberately low, so the first row describes this set, not how often a real",
        "model under-rates. What the set shows is which under-ratings each rule catches.",
        "",
        "| Rule | Cases rated | Under-rated | Over-rated |",
        "|---|---:|---:|---:|",
    ]
    for rule in RULES:
        row = summary[rule]
        if row["rated"] == 0:
            lines.append(f"| {LABELS[rule]} | not measured | — | — |")
        else:
            lines.append(f"| {LABELS[rule]} | {row['rated']} | {row['under']} | {row['over']} |")

    answered = summary["assessor_answered"]["rated"]
    lines += [""]
    if answered < total:
        lines += [
            f"The assessor answered {answered} of {total} cases. Rows that need it cover only",
            "those. Record its answers with `python -m drdoom.evals.risk --record` against a",
            "configured provider.",
            "",
        ]
    for rule in RULES:
        if summary[rule]["under_ids"]:
            ids = ", ".join(f"`{case}`" for case in summary[rule]["under_ids"])
            lines.append(f"- Still under-rated by *{LABELS[rule]}*: {ids}")
    lines += [
        "",
        "## Per case",
        "",
        "| Case | Should be | Author | Floor | Assessor |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| `{r.case_id}` | {r.expected} | {r.author} | {r.floor} | {r.assessor or '—'} |"
        for r in results
    ]
    return "\n".join(lines) + "\n"


def build_provider_for(record: bool, provider_name: str) -> LLMProvider:
    store = SnapshotStore(snapshot_dir())
    if not record:
        return ReplayProvider(store)

    from drdoom.llm.factory import build_provider

    return RecordingProvider(build_provider(provider_name), store, note="risk eval")


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Score how risk ratings are decided.")
    parser.add_argument("--record", action="store_true", help="call a real provider")
    parser.add_argument("--provider", default="groq")
    parser.add_argument("--out", type=Path, default=None)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    assessor = RiskAssessor(build_provider_for(args.record, args.provider))
    results = [run_case(assessor, case) for case in load_cases()]
    summary = summarise(results)

    docs = args.out or get_settings().project_root / "docs"
    docs.mkdir(parents=True, exist_ok=True)
    (docs / "risk-results.md").write_text(render(summary, results), encoding="utf-8")
    for rule in RULES:
        logger.info("%-18s %s", rule, summary[rule])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
